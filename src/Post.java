import java.util.*;
class Post {
        int id;
        String date;
        String category;
        String title;
        String content;
        Post(int id, String date, String category, String title, String content){
            this.id=id;
            this.date=date;
            this.category=category;
            this.title=title;
            this.content=content;
        }
    }